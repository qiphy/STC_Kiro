-- Bank Cyber Recovery Platform: schema (Supabase / Postgres)
-- Run in the Supabase SQL editor. Safe to re-run: drops and recreates everything.

drop table if exists notifications, advisories, tasks, incident_services, incidents,
  service_dependencies, alt_channels, technicians, services cascade;

create table services (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text not null default '',
  criticality int not null check (criticality between 1 and 5),
  customer_impact int not null check (customer_impact between 1 and 5),
  status text not null default 'operational'
    check (status in ('operational', 'degraded', 'down', 'recovering')),
  severity text not null default 'low'
    check (severity in ('low', 'medium', 'high', 'critical'))
);

create table service_dependencies (
  service_id bigint not null references services(id) on delete cascade,
  depends_on_id bigint not null references services(id) on delete cascade,
  primary key (service_id, depends_on_id),
  check (service_id <> depends_on_id)
);

create table technicians (
  id bigint generated by default as identity primary key,
  name text not null,
  role text not null,
  email text not null
);

create table incidents (
  id bigint generated by default as identity primary key,
  title text not null,
  status text not null default 'active' check (status in ('active', 'resolved')),
  started_at timestamptz not null default now(),
  resolved_at timestamptz
);

create table incident_services (
  incident_id bigint not null references incidents(id) on delete cascade,
  service_id bigint not null references services(id) on delete cascade,
  primary key (incident_id, service_id)
);

create table tasks (
  id bigint generated by default as identity primary key,
  incident_id bigint not null references incidents(id) on delete cascade,
  service_id bigint not null references services(id) on delete cascade,
  title text not null,
  technician_id bigint references technicians(id) on delete set null,
  status text not null default 'todo'
    check (status in ('todo', 'in_progress', 'done', 'blocked'))
);

create table advisories (
  id bigint generated by default as identity primary key,
  incident_id bigint not null references incidents(id) on delete cascade,
  title text not null,
  body text not null,
  status text not null default 'draft' check (status in ('draft', 'published')),
  created_at timestamptz not null default now()
);

create table notifications (
  id bigint generated by default as identity primary key,
  incident_id bigint not null references incidents(id) on delete cascade,
  audience text not null check (audience in ('customers', 'technicians')),
  message text not null,
  sent_at timestamptz not null default now() -- simulated send, nothing leaves the system
);

create table alt_channels (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null,
  contact text not null,
  verified boolean not null default false
);

create index on tasks (incident_id);
create index on tasks (technician_id);
create index on notifications (incident_id);

-- The backend uses the service role key, which bypasses RLS.
-- Enabling RLS with no policies blocks anyone using the public anon key.
alter table services enable row level security;
alter table service_dependencies enable row level security;
alter table technicians enable row level security;
alter table incidents enable row level security;
alter table incident_services enable row level security;
alter table tasks enable row level security;
alter table advisories enable row level security;
alter table notifications enable row level security;
alter table alt_channels enable row level security;
